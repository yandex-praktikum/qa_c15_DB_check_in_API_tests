def test_delete_courier(api, courier):
    """
    Проверяем успешное удаление курьера через API.

    Курьер и связанные с ним тестовые данные
    создаются фикстурой courier.
    """

    response = api.delete_courier(courier)

    # Проверяем, что API сообщает об успешном удалении курьера.
    assert response.status_code == 200

