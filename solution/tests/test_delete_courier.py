def test_delete_courier(api, db, courier):
    """
    Проверяем удаление курьера через API
    и фактическое состояние связанных данных в БД.

    Фикстура courier:
    - создаёт тестового курьера;
    - создаёт связанный с ним заказ;
    - возвращает courier_id;
    - очищает тестовые данные после выполнения теста.
    """

    # Шаг 1. Удаляем курьера через API.
    response = api.delete_courier(courier)

    # API сообщает об успешном удалении.
    assert response.status_code == 200

    # Шаг 2. Проверяем БД.
    # Эта проверка не дублирует ответ API:
    # она позволяет узнать, что произошло со связанными заказами.
    orders = db.get_orders_by_courier(courier)

    # После удаления курьера связанных заказов быть не должно.
    #
    # Если проверка падает, это не обязательно ошибка теста.
    # На стенде может обнаружиться расхождение между поведением API
    # и фактическим состоянием данных в БД.
    assert orders == []